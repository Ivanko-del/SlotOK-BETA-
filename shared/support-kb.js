function supportNormalize(text) {
  return String(text || '').toLowerCase().replace(/[’ʼ`]/g, "'").replace(/\s+/g, ' ').trim();
}

// Найкраща тема: довші й точніші фрагменти важать більше.
function supportMatch(text) {
  const t = ' ' + supportNormalize(text) + ' ';
  let best = null, bestScore = 0;
  for (const topic of SUPPORT_TOPICS) {
    let score = 0;
    for (const k of topic.keys) if (t.includes(k)) score += 1 + k.length / 8;
    if (score > bestScore) { bestScore = score; best = topic; }
  }
  return best ? { topic: best, score: bestScore } : null;
}

function supportTopic(id) {
  for (const t of SUPPORT_TOPICS) if (t.id === id) return t;
  return null;
}

function supportPick(list, n) {
  if (!list || !list.length) return '';
  const i = typeof n === 'number' ? Math.abs(n) % list.length : Math.floor(Math.random() * list.length);
  return list[i];
}

